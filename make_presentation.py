from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor

prs = Presentation()
prs.slide_width = Inches(13.33)
prs.slide_height = Inches(7.5)

BG_COLOR = RGBColor(250, 248, 245)
TEXT_MAIN = RGBColor(44, 62, 80)
ACCENT_MINT = RGBColor(15, 155, 142)

BLANK = prs.slide_layouts[6]

def create_slide(title_text):
    slide = prs.slides.add_slide(BLANK)
    fill = slide.background.fill
    fill.solid()
    fill.fore_color.rgb = BG_COLOR
    txBox = slide.shapes.add_textbox(Inches(0.5), Inches(0.4), Inches(12.33), Inches(0.8))
    tf = txBox.text_frame
    tf.word_wrap = True
    p = tf.paragraphs[0]
    p.text = title_text
    p.font.name = "Segoe UI"
    p.font.size = Pt(28)
    p.font.color.rgb = ACCENT_MINT
    return slide

def add_block(slide, left, top, width, height, lines):
    txBox = slide.shapes.add_textbox(Inches(left), Inches(top), Inches(width), Inches(height))
    tf = txBox.text_frame
    tf.word_wrap = True
    for i, line in enumerate(lines):
        if i == 0:
            p = tf.paragraphs[0]
            p.text = line
            p.font.name = "Segoe UI"
            p.font.size = Pt(16)
            p.font.bold = True
            p.font.color.rgb = ACCENT_MINT
            p.space_after = Pt(12)
        else:
            p = tf.add_paragraph()
            p.text = line
            p.font.name = "Segoe UI"
            p.font.size = Pt(14)
            p.font.color.rgb = TEXT_MAIN
            p.space_after = Pt(8)

